def copy_is_generic(text: Any) -> bool:
    value = str(text or "").strip()
    return any(
        pattern.fullmatch(value)
        for pattern in (*GENERIC_SUMMARY_PATTERNS, *GENERIC_STORY_HOOK_PATTERNS)
    )


