"""Shared player-facing copy for card candidates (C6 M1/M2).

This module is the single place that converts world preset candidates into
safe, budgeted player text.  Both rendering chains consume the DTOs built
here:

- the interactive prompt chain (``tavern/presentation.py``), and
- the proactive delivery chain (``tavern/card_delivery.py``).

Neither chain interprets raw world mappings any more, so internal contract
fields (``id``/``text_id``/``rule_refs``/``source_refs``/``contract``/...)
can never leak into player-visible copy.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from ..candidates import (
    CANDIDATE_RULE_KEYS,
    normalize_candidate_rules,
)


class CandidateCopyError(ValueError):
    """World content error: a candidate cannot produce valid player copy."""


